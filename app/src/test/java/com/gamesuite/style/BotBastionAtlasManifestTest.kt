/**
 * Validates the baked-isometric Bot Bastion sprite pack (assets/styles/bot-bastion/manifest.json), produced by
 * scripts/bake_bot_bastion_atlas.py (SPEC.md test R9): every frame lies inside its atlas, anchors are sane,
 * atlas hashes and sizes match the files, the total stays under the 6 MB ceiling, and the full Phase 1 roster
 * is present (all bots with 5 levels, enemies and bosses, Core states, FX, 4 sectors in 3 lit variants).
 */
class BotBastionAtlasManifestTest {
    private val dir: File = listOf(File("src/main/assets/styles/bot-bastion"), File("app/src/main/assets/styles/bot-bastion"))
        .firstOrNull { it.isDirectory } ?: error("styles/bot-bastion assets not found")
    private val manifest: JsonObject = Json.parseToJsonElement(File(dir, "manifest.json").readText()).jsonObject
    private val frames: JsonArray = manifest["frames"]!!.jsonArray
    private val atlases: JsonArray = manifest["atlases"]!!.jsonArray

    private fun JsonObject.s(k: String) = this[k]!!.jsonPrimitive.content
    private fun JsonObject.i(k: String) = this[k]!!.jsonPrimitive.int
    private fun JsonObject.d(k: String) = this[k]!!.jsonPrimitive.content.toDouble()

    /** Pixel size from a WebP header (VP8X, lossy VP8 or lossless VP8L), no image decoder needed. */
    private fun webpSize(b: ByteArray): Pair<Int, Int> {
        fun le16(o: Int) = (b[o].toInt() and 0xff) or ((b[o + 1].toInt() and 0xff) shl 8)
        fun le24(o: Int) = le16(o) or ((b[o + 2].toInt() and 0xff) shl 16)
        assertEquals("RIFF", String(b, 0, 4)); assertEquals("WEBP", String(b, 8, 4))
        return when (val fourcc = String(b, 12, 4)) {
            "VP8X" -> (le24(24) + 1) to (le24(27) + 1)
            "VP8 " -> (le16(26) and 0x3fff) to (le16(28) and 0x3fff)
            "VP8L" -> {
                val bits = (b[21].toLong() and 0xff) or ((b[22].toLong() and 0xff) shl 8) or
                    ((b[23].toLong() and 0xff) shl 16) or ((b[24].toLong() and 0xff) shl 24)
                (((bits and 0x3fff) + 1).toInt()) to ((((bits shr 14) and 0x3fff) + 1).toInt())
            }
            else -> error("unknown WebP chunk $fourcc")
        }
    }

    @Test fun schemaAndLicenceAreDeclared() {
        assertEquals(1, manifest.i("schema"))
        assertTrue(manifest.s("license").contains("original, generated by project scripts"))
        val bake = manifest["bake"]!!.jsonObject
        assertEquals(50.0, bake.d("elevationDeg"), 0.0)
        assertEquals(8, bake.i("facings"))
    }

    @Test fun atlasFilesMatchTheirHashSizeAndDimensions() {
        var total = 0L
        for (a in atlases.map { it.jsonObject }) {
            val f = File(dir, a.s("file"))
            assertTrue("missing ${f.name}", f.isFile)
            val bytes = f.readBytes()
            assertEquals(f.name, a["bytes"]!!.jsonPrimitive.long, bytes.size.toLong())
            assertEquals(f.name, a.s("sha256"), MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) })
            assertEquals(f.name, a.i("width") to a.i("height"), webpSize(bytes))
            assertTrue("${f.name} larger than 2048 px", a.i("width") <= 2048 && a.i("height") <= 2048)
            total += bytes.size
        }
        assertEquals(manifest["totalBytes"]!!.jsonPrimitive.long, total)
        val onDisk = dir.listFiles { x -> x.extension == "webp" }!!.map { it.name }.toSet()
        assertEquals(atlases.map { it.jsonObject.s("file") }.toSet(), onDisk)
    }

    @Test fun totalSizeIsUnderTheSixMegabyteCeiling() {
        val total = dir.listFiles()!!.filter { it.isFile }.sumOf { it.length() }
        assertTrue("pack is $total bytes", total <= 6L * 1024 * 1024)
    }

    @Test fun everyFrameIsInsideItsAtlasWithoutOverlapAndAnchorsAreInRange() {
        val dims = atlases.associate { it.jsonObject.s("id") to (it.jsonObject.i("width") to it.jsonObject.i("height")) }
        val groups = manifest["groups"]!!.jsonObject
        val ids = HashSet<String>()
        val byAtlas = HashMap<String, MutableList<IntArray>>()
        for (f in frames.map { it.jsonObject }) {
            val id = f.s("id")
            assertTrue("duplicate id $id", ids.add(id))
            val (aw, ah) = dims[f.s("atlas")] ?: error("$id: unknown atlas ${f.s("atlas")}")
            val x = f.i("x"); val y = f.i("y"); val w = f.i("w"); val h = f.i("h")
            assertTrue("$id empty rect", w > 0 && h > 0)
            assertTrue("$id outside atlas", x >= 0 && y >= 0 && x + w <= aw && y + h <= ah)
            val g = groups[f.s("group")]?.jsonObject ?: error("$id: group ${f.s("group")} undeclared")
            val kind = g.s("kind")
            val ax = f.d("ax"); val ay = f.d("ay")
            // ground-contact anchor must sit inside the sprite for grounded bodies/bases/props; turret heads and
            // rotors (drawn above the base), flyers, FX, decals and backdrops may anchor outside by up to one sprite size
            val tight = (f.s("part") == "base" || f.s("part") == "body") && (kind == "unit" || kind == "prop" || kind == "marker" || kind == "tile" || kind == "plate") && g["flying"] == null
            val mx = if (tight) 1.0 else w.toDouble()
            val my = if (tight) 1.0 else h.toDouble()
            assertTrue("$id anchor ($ax,$ay) out of range for ${w}x$h", ax >= -mx && ax <= w + mx && ay >= -my && ay <= h + my)
            assertTrue("$id facing", f.i("facing") in 0..7)
            assertTrue("$id level", f.i("level") in 1..5)
            byAtlas.getOrPut(f.s("atlas")) { mutableListOf() }.add(intArrayOf(x, y, x + w, y + h))
        }
        for ((atlas, rects) in byAtlas) {
            for (i in rects.indices) for (j in i + 1 until rects.size) {
                val a = rects[i]; val b = rects[j]
                if (a[0] < b[2] && b[0] < a[2] && a[1] < b[3] && b[1] < a[3]) fail("overlap in $atlas: ${a.toList()} vs ${b.toList()}")
            }
        }
        // group frame counts agree with the frame list
        val counts = frames.groupingBy { it.jsonObject.s("group") }.eachCount()
        for ((name, g) in groups) assertEquals(name, g.jsonObject.i("frames"), counts[name] ?: 0)
        assertEquals(counts.keys, groups.keys)
    }

    private fun framesOf(group: String) = frames.map { it.jsonObject }.filter { it.s("group") == group }

    @Test fun botsHaveFiveLevelLooksAndEightFacingHeads() {
        for (bot in listOf("picket", "lobber", "haze")) {
            val fs = framesOf(bot)
            for (lv in 1..5) {
                assertEquals("$bot L$lv base", 1, fs.count { it.s("part") == "base" && it.i("level") == lv })
                assertEquals("$bot L$lv heads", (0..7).toList(), fs.filter { it.s("part") == "head" && it.i("level") == lv }.map { it.i("facing") }.sorted())
            }
        }
        for (lv in 1..5) {
            val t = framesOf("tender")
            assertEquals(1, t.count { it.s("part") == "base" && it.i("level") == lv })
            assertEquals(4, t.count { it.s("part") == "rotor" && it.i("level") == lv })
            val s = framesOf("skiff")
            assertEquals((0..7).toList(), s.filter { it.i("level") == lv }.map { it.i("facing") }.sorted())
        }
        assertEquals(1, framesOf("aegis").size)
        assertEquals(listOf(0, 1, 2, 3), framesOf("core").map { it.i("frame") }.sorted())
        assertEquals(3, framesOf("shield_dome").size)
    }

    @Test fun enemiesAndBossesHaveEightFacingsByFourTumbleFrames() {
        val units = listOf("drifter", "darter", "plater", "splitter", "bit", "courier",
            "behemoth_base", "behemoth_slag", "behemoth_gilded", "behemoth_crimson")
        val groups = manifest["groups"]!!.jsonObject
        for (u in units) {
            val fs = framesOf(u)
            assertEquals(u, 32, fs.size)
            for (k in 0..7) assertEquals("$u f$k", listOf(0, 1, 2, 3), fs.filter { it.i("facing") == k }.map { it.i("frame") }.sorted())
            val r = groups[u]!!.jsonObject.d("footprintRadiusU")
            assertTrue("$u footprint $r", r in 0.1..1.5)
        }
    }

    @Test fun projectilesFxAndDecalsExist() {
        for (g in listOf("proj_pew", "proj_skiff", "proj_hiss")) assertEquals(g, 8, framesOf(g).size)
        for (g in listOf("proj_shell", "shadow_blob", "glow_s", "glow_m", "glow_l", "range_solid", "range_dashed", "range_dotted",
            "range_double", "range_blindspot", "fx_muzzle_cyan", "fx_muzzle_amber", "fx_muzzle_violet", "fx_muzzle_magenta")) assertEquals(g, 1, framesOf(g).size)
        for (g in listOf("fx_explosion", "fx_pop", "fx_spark", "fx_dust", "fx_freeze", "fx_nova_ring", "fx_repair", "fx_build_ring", "crate")) {
            assertTrue("$g frames", framesOf(g).size >= 6)
        }
        assertEquals(2, framesOf("fx_hit_flash").size)
    }

    @Test fun fourSectorsHaveEveryLitVariant() {
        val sectors = listOf("cradle", "glass", "ember", "hush")
        val lights = listOf("dusk", "night", "alarm")
        for (s in sectors) for (l in lights) {
            val fs = frames.map { it.jsonObject }.filter { it["sector"]?.jsonPrimitive?.content == s && it["light"]?.jsonPrimitive?.content == l }
            fun n(group: String) = fs.count { it.s("group") == group }
            assertEquals("$s/$l plate", 1, n("plate"))
            for (layer in listOf("backdrop_far", "backdrop_mid", "backdrop_near")) assertEquals("$s/$l $layer", 1, n(layer))
            for (t in listOf("ground_a", "ground_b", "ground_c", "lane_h", "lane_v", "lane_ne", "lane_se", "lane_sw", "lane_nw")) assertEquals("$s/$l $t", 1, n("tile_$t"))
            for (p in listOf("empty", "selected", "valid", "invalid")) assertEquals("$s/$l pad_$p", 1, n("pad_$p"))
            assertEquals("$s/$l gates", 4, n("gate"))
            assertEquals("$s/$l props", 12, fs.map { it.s("group") }.distinct().count { it.startsWith("prop_") })
        }
    }
}
