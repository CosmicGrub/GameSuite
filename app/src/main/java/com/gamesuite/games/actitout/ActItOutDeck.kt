package com.gamesuite.games.actitout

/** The card families. [id] is stable (saved nowhere, but used in tests and docs). */
enum class ActItOutCategory(val id: String) {
    ANIMALS("animals"),
    ACTIONS("actions"),
    EVERYDAY("everyday"),
    SCENES("scenes"),
    SPORTS("sports"),
    FEELINGS("feelings"),

    /** "Hard mode": abstract and tricky ideas, all difficulty 3. */
    HARD("hard")
}

/**
 * One prompt. [difficulty] is 1 (every difficulty-1 card has a picture of its very own, so a pre-reader can play
 * from the picture), 2 or 3. [glyph] names a drawing in [ActItOutGlyphs]; harder cards use their category's emblem.
 * [english] is the source text; the shown text is the string resource [stringName] in the current language
 * (res/values and values-es, kept in step with this list by a test).
 */
data class ActItOutCard(
    val id: String,
    val category: ActItOutCategory,
    val difficulty: Int,
    val glyph: String,
    val english: String
) {
    val stringName: String get() = "act_it_out_card_$id"
}

