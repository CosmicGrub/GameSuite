#!/usr/bin/env python3
"""Bake the Bot Bastion baked-isometric sprite pack (Phase 1 assets).

Original art, generated by project scripts: Blender models in scripts/bot_bastion_3d/bb_units.py and bb_sectors.py,
procedural FX in bb_procedural.py. No downloaded models, textures, fonts or HDRIs.

Usage:
    python scripts/bake_bot_bastion_atlas.py [--raw DIR] [--skip-blender] [--out DIR] [--budget-mb 6]

Stage 1 runs Blender headless (BLENDER env var, else the standard install path, else `blender` on PATH) and writes
2x-supersampled PNG frames to --raw. Stage 2 downsamples, outlines and trims every frame, adds the procedural FX,
shelf-packs atlases (WebP, lossy+alpha) and writes manifest.json next to them. The size gate fails if the total
exceeds --budget-mb (default 6): quality is stepped down first, then the script errors.
Requires Pillow (with WebP) and numpy for stage 2.
"""
import argparse, hashlib, json, os, subprocess, sys, tempfile, glob, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "bot_bastion_3d"))
REPO = os.path.dirname(HERE)
DEFAULT_OUT = os.path.join(REPO, "app", "src", "main", "assets", "styles", "bot-bastion")

from PIL import Image, ImageFilter  # noqa: E402
import numpy as np  # noqa: E402

SS = 2
INK = (14, 18, 38)

# game-unit footprint radius of each unit group (ground contact), used by the renderer for picking and shadows
FOOTPRINT = {"picket": 0.46, "lobber": 0.53, "haze": 0.48, "tender": 0.48, "skiff": 0.42, "aegis": 0.42, "core": 1.05,
             "drifter": 0.42, "darter": 0.34, "plater": 0.46, "splitter": 0.46, "bit": 0.26, "courier": 0.42,
             "behemoth_base": 0.9, "behemoth_slag": 0.9, "behemoth_gilded": 0.9, "behemoth_crimson": 0.9}
BOTS = ("picket", "lobber", "haze", "tender", "skiff", "aegis")
SECTOR_NAMES = {"cradle": 1, "glass": 2, "ember": 3, "hush": 4}
LIGHTS = ("dusk", "night", "alarm")


def find_blender():
    if os.environ.get("BLENDER"):
        return os.environ["BLENDER"]
    for p in glob.glob(r"C:\Program Files\Blender Foundation\Blender *\blender.exe"):
        return p
    return shutil.which("blender") or "blender"


def run_blender(raw):
    os.makedirs(raw, exist_ok=True)
    cmd = [find_blender(), "-b", "--python", os.path.join(HERE, "bot_bastion_3d", "bb_bake.py"), "--", raw]
    print("running", " ".join(cmd))
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)


def atlas_for(meta):
    g = meta["group"]
    if meta.get("sector"):
        return "sector_" + meta["sector"]
    if g in BOTS or g == "core":
        return "bots"
    if g.split("_")[0] in ("drifter", "darter", "plater", "splitter", "bit", "courier", "behemoth") and not g.startswith("fx_"):
        return "enemies"
    return "fx"


def outline(im):
    """1 px dark ink outline (spec: optional dark outline on bots and enemies for phone readability)."""
    a = im.getchannel("A")
    grown = a.filter(ImageFilter.MaxFilter(3))
    base = Image.new("RGBA", im.size, INK + (0,))
    base.putalpha(grown.point(lambda v: min(255, int(v * 0.9))))
    return Image.alpha_composite(base, im)


def load_blender_frames(raw):
    frames = []
    for idx in sorted(glob.glob(os.path.join(raw, "index.*.json"))):
        for rec in json.load(open(idx)):
            path = os.path.join(raw, rec["name"] + ".png")
            im = Image.open(path).convert("RGBA")
            im = im.resize((rec["w"], rec["h"]), Image.LANCZOS)
            ax, ay = rec["ax"], rec["ay"]
            if rec.get("outline"):
                pad = 2
                big = Image.new("RGBA", (im.width + 2 * pad, im.height + 2 * pad), (0, 0, 0, 0))
                big.paste(im, (pad, pad))
                im = outline(big)
                ax += pad
                ay += pad
            meta = {k: rec[k] for k in rec if k not in ("name", "w", "h", "ax", "ay", "ppu", "outline")}
            meta.update(ppu=rec["ppu"], anchor=(ax, ay))
            frames.append((rec["name"], im, meta))
    return frames


def finalize(frames):
    """trim, anchor-adjust, classify; returns list of dict(id, img, meta)."""
    out = []
    for name, im, meta in frames:
        meta = dict(meta)
        meta.setdefault("ppu", 100.0)
        meta.setdefault("level", 1)
        meta.setdefault("facing", 0)
        meta.setdefault("frame", 0)
        meta.setdefault("part", "body")
        meta.setdefault("anim", "static")
        ax, ay = meta.pop("anchor", None) or (im.width / 2, im.height / 2)
        if not meta.pop("notrim", False):
            alpha = np.asarray(im.getchannel("A"))
            ys, xs = np.where(alpha > 6)
            if len(xs) == 0:  # fully faded last frame of an FX strip: keep a tiny transparent rect
                x0, x1, y0, y1 = 0, 2, 0, 2
            else:
                x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
            im = im.crop((x0, y0, x1, y1))
            ax -= x0
            ay -= y0
        meta["anchor"] = (round(float(ax), 1), round(float(ay), 1))
        out.append(dict(id=name, img=im, meta=meta))
    return out


def shelf_pack(items, name, maxw=2048, maxh=2048, pad=2):
    """returns list of (atlas_name, [(item, x, y)], w, h). Splits into name, name2.. if maxh is exceeded."""
    items = sorted(items, key=lambda it: (-it["img"].height, -it["img"].width, it["id"]))
    atlases, cur, x, y, rowh, wmax = [], [], pad, pad, 0, 0
    for it in items:
        w, h = it["img"].size
        if x + w + pad > maxw:
            x, y, rowh = pad, y + rowh + pad, 0
        if y + h + pad > maxh:
            atlases.append((cur, wmax, y + rowh + pad))
            cur, x, y, rowh, wmax = [], pad, pad, 0, 0
        cur.append((it, x, y))
        x += w + pad
        rowh = max(rowh, h)
        wmax = max(wmax, x)
    if cur:
        atlases.append((cur, wmax, y + rowh + pad))
    res = []
    for i, (lst, w, h) in enumerate(atlases):
        res.append((name if i == 0 else f"{name}{i + 1}", lst, (w + 3) // 4 * 4, (h + 3) // 4 * 4))
    return res


def group_meta(frames_by_group):
    groups = {}
    for g, fs in frames_by_group.items():
        m0 = fs[0]["meta"]
        gm = {"kind": m0.get("kind", "unit"), "ppu": m0["ppu"], "frames": len(fs),
              "facings": sorted({f["meta"]["facing"] for f in fs}),
              "levels": sorted({f["meta"]["level"] for f in fs}),
              "parts": sorted({f["meta"]["part"] for f in fs}),
              "anims": sorted({f["meta"]["anim"] for f in fs})}
        base = g.replace("_", " ").split()[0]
        if g in FOOTPRINT:
            gm["footprintRadiusU"] = FOOTPRINT[g]
        if m0.get("flying"):
            gm["flying"] = True
        if m0.get("blend"):
            gm["blend"] = m0["blend"]
        if m0.get("baked_radius_u"):
            gm["bakedRadiusU"] = m0["baked_radius_u"]
        if m0.get("parallax") is not None:
            gm["parallax"] = m0["parallax"]
        gm["maxAboveAnchorPx"] = int(round(max(f["meta"]["anchor"][1] for f in fs)))
        groups[g] = gm
    return groups


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=os.path.join(tempfile.gettempdir(), "bb-raw"))
    ap.add_argument("--skip-blender", action="store_true")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--budget-mb", type=float, default=6.0)
    a = ap.parse_args()
    if not a.skip_blender:
        if os.path.isdir(a.raw):
            for f in glob.glob(os.path.join(a.raw, "*")):
                os.remove(f)
        run_blender(a.raw)
    import bb_procedural as P
    frames = load_blender_frames(a.raw) + P.fx_all() + P.backdrops()
    items = finalize(frames)
    # classify into atlases
    by_atlas = {}
    for it in items:
        m = it["meta"]
        if m.get("sector") is None and m["group"].startswith("backdrop"):
            raise SystemExit("backdrop without sector")
        by_atlas.setdefault(atlas_for(m), []).append(it)
    packed = []
    for name, its in sorted(by_atlas.items()):
        packed += shelf_pack(its, name)
    os.makedirs(a.out, exist_ok=True)
    for f in glob.glob(os.path.join(a.out, "*.webp")):
        os.remove(f)
    budget = int(a.budget_mb * 1024 * 1024)
    quality = {"bots": 92, "enemies": 90, "fx": 90}
    default_q = 88

    def write_all(scale_q):
        total = 0
        metas = []
        for name, lst, w, h in packed:
            canvas_im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
            for it, x, y in lst:
                canvas_im.paste(it["img"], (x, y))
            q = max(30, quality.get(name.rstrip("0123456789"), default_q) - scale_q)
            path = os.path.join(a.out, name + ".webp")
            canvas_im.save(path, "WEBP", quality=q, alpha_quality=min(100, q + 10), method=6)
            data = open(path, "rb").read()
            total += len(data)
            metas.append(dict(id=name, file=name + ".webp", width=w, height=h, format="webp-lossy-alpha", quality=q,
                              bytes=len(data), sha256=hashlib.sha256(data).hexdigest()))
        return total, metas

    scale_q = 0
    total, atlases = write_all(scale_q)
    while total > budget and scale_q < 40:
        scale_q += 6
        total, atlases = write_all(scale_q)
    if total > budget:
        raise SystemExit(f"SIZE GATE FAILED: {total} bytes > budget {budget}")
    placed = {}
    frames_out = []
    for name, lst, w, h in packed:
        for it, x, y in lst:
            m = it["meta"]
            fr = {"id": it["id"], "atlas": name, "x": x, "y": y, "w": it["img"].width, "h": it["img"].height,
                  "ax": m["anchor"][0], "ay": m["anchor"][1], "group": m["group"], "part": m["part"], "level": m["level"],
                  "facing": m["facing"], "anim": m["anim"], "frame": m["frame"]}
            if m.get("sector"):
                fr["sector"] = m["sector"]
                fr["light"] = m["light"]
            frames_out.append(fr)
    frames_out.sort(key=lambda f: f["id"])
    by_group = {}
    for it in items:
        by_group.setdefault(it["meta"]["group"], []).append(it)
    manifest = {
        "schema": 1,
        "pack": "bot-bastion-3d",
        "license": "original, generated by project scripts (Blender 5.1 headless + Pillow); no third-party assets",
        "bake": {"elevationDeg": 50.0, "yawDeg": 0.0, "projection": "orthographic", "ppu": 100.0, "supersample": SS,
                 "facings": 8, "facingConvention": "facing k = heading 45*k degrees counter-clockwise from screen-right (+x); +y is screen-up (away from viewer)",
                 "anchorConvention": "(ax, ay) = pixel inside the frame rect (origin top-left) where the ground-contact centre (model origin) sits",
                 "groundYScale": 0.766, "outline": "1px ink #0E1226 baked on bots and enemies", "lighting": "neutral dusk rig for units; sector rigs for environment",
                 "sectors": SECTOR_NAMES, "lights": list(LIGHTS), "tile": {"w": 100, "h": 77}},
        "budgetBytes": budget,
        "totalBytes": total,
        "atlases": atlases,
        "groups": group_meta(by_group),
        "frames": frames_out,
    }
    with open(os.path.join(a.out, "manifest.json"), "w") as fh:
        json.dump(manifest, fh, separators=(",", ":"))
    print(f"frames={len(frames_out)} atlases={len(atlases)} total={total/1024/1024:.2f} MB (budget {a.budget_mb} MB, quality -{scale_q})")
    for at in atlases:
        print(f"  {at['file']:28s} {at['width']}x{at['height']} {at['bytes']/1024:.0f} KB q{at['quality']}")


if __name__ == "__main__":
    main()
