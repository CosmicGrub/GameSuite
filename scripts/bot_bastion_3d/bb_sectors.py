"""Four sector environment sets (tiles, node pads, gates, props, arena plate) in three lit variants.
Original geometry, generated by project scripts. Imported by bb_bake.py (Blender)."""
import math
from bb_kit import *
import bb_kit

R = math.radians
GK = [1.0]


def eg(h, s):
    return gl(h, s * GK[0])


SECTORS = {
    "cradle": dict(world="#0E1226", ground="#1A2352", lane="#10173A", key=(1.0, 0.93, 0.82), rim=(0.45, 0.7, 1.0), acc="#4FE3FF"),
    "glass": dict(world="#0A1A24", ground="#16384A", lane="#0C2230", key=(0.85, 0.97, 1.0), rim=(0.5, 0.9, 1.0), acc="#9DEBFF"),
    "ember": dict(world="#1A0C0C", ground="#3A1A18", lane="#241010", key=(1.0, 0.75, 0.55), rim=(1.0, 0.45, 0.25), acc="#FF8A3D"),
    "hush": dict(world="#100A22", ground="#2A1E52", lane="#170F36", key=(0.85, 0.8, 1.0), rim=(0.7, 0.5, 1.0), acc="#B58CFF"),
}
LIGHTS = ("dusk", "night", "alarm")


def apply_light(sec, light):
    s = SECTORS[sec]
    k, r = s["key"], s["rim"]
    if light == "dusk":
        GK[0] = 1.0
        set_rig(k, r, 3.2, 1.6, 0.5, 0.0, s["world"])
    elif light == "night":
        GK[0] = 1.7
        set_rig((k[0] * 0.6, k[1] * 0.7, min(1.0, k[2] * 1.0)), (r[0], r[1], r[2]), 1.5, 2.4, 0.35, 0.0, s["world"], 0.5)
    else:
        GK[0] = 1.35
        set_rig(k, (min(1.0, r[0] * 0.6 + 0.4), r[1] * 0.6, r[2] * 0.6), 2.6, 1.5, 0.45, 2.4, s["world"])


TW, TH = 100, 77
TY = TH / (100 * math.sin(R(ELEV)))  # tile depth in world units so the projected tile is exactly 77 px


def ground_mats(sec):
    s = SECTORS[sec]
    return (mat("g_" + sec, hexrgb(s["ground"]), 0.92), mat("l_" + sec, hexrgb(s["lane"]), 0.8),
            eg(s["acc"], 1.1), mat("seam_" + sec, hexrgb(s["lane"]), 0.9))


def tile_base(gm, lm_seam, kind="ground", edges=()):
    p = [box("t", 1.0, TY, 0.02, (0, 0, -0.01), (0, 0, 0), gm)]
    return p


def build_tiles(sec, light):
    gm, lm, em, seam = ground_mats(sec)
    out = {}

    def seams(p):
        for sx, sy, lx, ly in ((0.04, TY, -0.48, 0), (0.04, TY, 0.48, 0), (1.0, 0.04, 0, -TY / 2 + 0.02), (1.0, 0.04, 0, TY / 2 - 0.02)):
            p.append(box("seam", sx, sy, 0.03, (lx, ly, 0.005), (0, 0, 0), seam))

    p = tile_base(gm, seam)
    seams(p)
    out["ground_a"] = join(p, "ga")
    p = tile_base(gm, seam)
    seams(p)
    for i in (-1, 1):
        p.append(box("vent", 0.34, 0.05, 0.03, (0.0, 0.14 * i, 0.01), (0, 0, 0), seam))
    p.append(box("dot", 0.06, 0.06, 0.03, (0.3, 0.0, 0.01), (0, 0, 0), em))
    out["ground_b"] = join(p, "gb")
    p = tile_base(gm, seam)
    seams(p)
    for sx in (-0.36, 0.36):
        for sy in (-0.3, 0.3):
            p.append(cyl("rivet", 0.04, 0.03, 6, (sx, sy, 0.012), (0, 0, 0), HULL2))
    p.append(box("plate", 0.5, 0.35, 0.02, (0, 0, 0.004), (0, 0, 0), mat("pl_" + sec, hexrgb(SECTORS[sec]["lane"]), 0.85)))
    out["ground_c"] = join(p, "gc")

    def lane(name, sides):
        q = tile_base(lm, seam)
        for sd in sides:
            if sd in "NS":
                q.append(box("edge", 1.0, 0.05, 0.05, (0, (TY / 2 - 0.04) * (1 if sd == "N" else -1), 0.02), (0, 0, 0), em))
            else:
                q.append(box("edge", 0.05, TY, 0.05, ((0.5 - 0.04) * (1 if sd == "E" else -1), 0, 0.02), (0, 0, 0), em))
        out[name] = join(q, name)

    lane("lane_h", "NS")      # lane runs east-west, edge lights north and south
    lane("lane_v", "EW")      # lane runs north-south
    lane("lane_ne", "WS")     # bend connecting the N and E sides: outer edges are W and S
    lane("lane_se", "NW")
    lane("lane_sw", "NE")
    lane("lane_nw", "SE")
    return out


def build_pad(sec, state):
    s = SECTORS[sec]
    pad_col = {"empty": HULL2, "selected": WHITE, "valid": mat("pv", hexrgb("#9FE8C8"), 0.4, 0.2), "invalid": mat("pi", hexrgb("#4A3A44"), 0.5, 0.2)}[state]
    ring = {"empty": eg(s["acc"], 0.9), "selected": eg(s["acc"], 1.8), "valid": gl("#6BFF9E", 1.3 * GK[0]), "invalid": gl("#FF6B5A", 1.4 * GK[0])}[state]
    p = [cyl("pad", 0.42, 0.08, 6, (0, 0, 0.04), (0, 0, R(30)), pad_col),
         cyl("ring", 0.5, 0.03, 6, (0, 0, 0.015), (0, 0, R(30)), ring),
         cyl("inner", 0.28, 0.02, 6, (0, 0, 0.09), (0, 0, R(30)), DARK if state != "selected" else ring)]
    if state == "selected":
        p.append(cyl("ring2", 0.58, 0.02, 6, (0, 0, 0.012), (0, 0, R(30)), ring))
    return join(p, "pad_" + state)


def build_gate(sec, k):
    s = SECTORS[sec]
    p = [box("post_l", 0.14, 0.14, 0.8, (-0.55, 0, 0.4), (0, 0, 0), HULL2), box("post_r", 0.14, 0.14, 0.8, (0.55, 0, 0.4), (0, 0, 0), HULL2),
         box("beam", 1.3, 0.16, 0.14, (0, 0, 0.82), (0, 0, 0), HULL),
         box("chev1", 0.5, 0.06, 0.07, (-0.14, 0, 0.82 - 0.0), (0, 0, 0), eg(s["acc"], 2.4))]
    for sgn in (-1, 1):
        p.append(box("lamp", 0.1, 0.1, 0.1, (0.55 * sgn, 0, 0.86), (0, 0, 0), eg("#FF6B5A", 2.2)))
    p.append(box("glow", 0.9, 0.5, 0.01, (0, 0, 0.01), (0, 0, 0), eg(s["acc"], 0.35)))
    o = join(p, "gate")
    o.rotation_euler = (0, 0, R(45 * k))
    return o


