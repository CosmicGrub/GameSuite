def props_ember():
    cap = eg("#FF8A3D", 2.6)
    slag = mat("pr_slag", hexrgb("#2E1A18"), 0.95)
    metal = mat("pr_met", hexrgb("#4A3A38"), 0.5, 0.5)

    def vent(r, h):
        return [cyl("v", r, h, 7, (0, 0, h / 2), (0, 0, 0), DARK, r2=r * 0.5), sph("g", r * 0.5, (0, 0, h + 0.03), 8, 4, (1, 1, 0.6), cap)]

    def fins(n):
        return [box("f", 0.7, 0.05, 0.5, (0, 0.12 * (i - n / 2), 0.3), (0, 0, 0), metal) for i in range(n)] + [box("b", 0.8, 0.9, 0.06, (0, 0, 0.03), (0, 0, 0), DARK)]

    def slg(seed, r):
        return [ico("s", r, (0, 0, r * 0.6), slag, 1, jitter=0.5, seed=seed), box("v", 0.05, r * 1.5, 0.05, (0, 0, r * 1.1), (0, 0, R(20)), cap)]

    def rack(n):
        return [cyl("p", 0.07, 0.8, 6, (0.8 * 0.0, 0.2 * (i - n / 2), 0.4 + 0.0 * i), (0, R(90), 0), metal) for i in range(n)] + [box("s", 0.06, 0.06, 0.6, (-0.35, 0, 0.3), (0, 0, 0), DARK), box("s2", 0.06, 0.06, 0.6, (0.35, 0, 0.3), (0, 0, 0), DARK)]

    return [("vent_a", vent(0.4, 0.4)), ("vent_b", vent(0.3, 0.55)), ("vent_c", vent(0.5, 0.3)), ("fins_a", fins(4)), ("fins_b", fins(6)),
            ("slag_a", slg(1, 0.4)), ("slag_b", slg(2, 0.32)), ("slag_c", slg(3, 0.5)), ("pipe_rack_a", rack(3)), ("pipe_rack_b", rack(4)),
            ("brazier", [cyl("b", 0.25, 0.3, 6, (0, 0, 0.15), (0, 0, 0), metal, r2=0.35), sph("f", 0.22, (0, 0, 0.42), 8, 5, (1, 1, 1.3), cap)]),
            ("pipe_stack", [cyl("p", 0.14, 0.9, 6, (-0.12, 0, 0.45), (0, 0, 0), metal), cyl("q", 0.1, 0.6, 6, (0.14, 0.05, 0.3), (0, 0, 0), DARK), sph("g", 0.1, (-0.12, 0, 0.95), 6, 4, (1, 1, 1), cap)])]


def props_hush():
    lam = eg("#E8DCFF", 2.4)
    vio = eg("#B58CFF", 1.8)
    moss = eg("#7AE0B0", 1.2)
    dk = mat("pr_hd", hexrgb("#2A2A4A"), 0.6, 0.3)

    def lantern(h, g):
        return [box("p", 0.05, 0.05, h, (0, 0, h / 2), (0, 0, 0), HULL2), sph("g", g, (0, 0, h + g * 0.6), 8, 5, (1, 1, 1), lam), cyl("c", 0.1, 0.08, 6, (0, 0, h), (0, 0, 0), HULL)]

    def buoy(z):
        return [sph("b", 0.24, (0, 0, z), 8, 5, (1, 1, 1), dk), torus("r", 0.3, 0.03, (0, 0, z), (R(70), 0, 0), vio, 12, 3), sph("l", 0.08, (0, 0, z + 0.26), 6, 4, (1, 1, 1), lam)]

    def ring(rot):
        return [torus("d", 0.5, 0.07, (0, 0, 0.55), (R(rot), 0, R(20)), dk, 14, 4), torus("e", 0.5, 0.025, (0, 0, 0.55), (R(rot), 0, R(20)), vio, 14, 3)]

    def mosses(seed):
        rr = random.Random(seed)
        return [cyl("m", 0.1, 0.3 + rr.random() * 0.3, 5, (rr.uniform(-.25, .25), rr.uniform(-.2, .2), 0.2), (rr.uniform(-.3, .3), 0, 0), moss if i % 2 == 0 else vio, r2=0.0) for i in range(5)]

    return [("lantern_a", lantern(0.9, 0.17)), ("lantern_b", lantern(1.1, 0.2)), ("lantern_c", lantern(0.6, 0.14)), ("buoy_a", buoy(0.5)), ("buoy_b", buoy(0.75)),
            ("derelict_ring_a", ring(75)), ("derelict_ring_b", ring(40)), ("moss_a", mosses(1)), ("moss_b", mosses(2)), ("moss_c", mosses(3)),
            ("spire", [cyl("s", 0.2, 0.9, 5, (0, 0, 0.45), (0, 0, 0), dk, r2=0.08), sph("t", 0.14, (0, 0, 1.0), 8, 5, (1, 1, 1), vio)]),
            ("lantern_pair", lantern(0.8, 0.14)[:2] + [box("p2", 0.05, 0.05, 0.6, (0.4, 0.1, 0.3), (0, 0, 0), HULL2), sph("g2", 0.12, (0.4, 0.1, 0.65), 8, 5, (1, 1, 1), lam)])]


PROPS = {"cradle": props_cradle, "glass": props_glass, "ember": props_ember, "hush": props_hush}


def build_plate(sec):
    s = SECTORS[sec]
    gm, lm, em, seam = ground_mats(sec)
    rim = DARK
    p = [box("plate", 17.2, 10.2, 0.3, (0, 0, -0.15), (0, 0, 0), gm), box("rim", 17.7, 10.7, 0.24, (0, 0, -0.3), (0, 0, 0), rim)]
    for x in range(-8, 9):
        p.append(box("sx", 0.03, 10.2, 0.02, (x + 0.0, 0, 0.004), (0, 0, 0), seam))
    for y in range(-5, 6):
        p.append(box("sy", 17.2, 0.03, 0.02, (0, y * 1.0, 0.004), (0, 0, 0), seam))
    # glowing inner edge strips
    for sy in (-1, 1):
        p.append(box("e", 17.0, 0.05, 0.03, (0, 5.0 * sy, 0.01), (0, 0, 0), em))
    for sx in (-1, 1):
        p.append(box("e", 0.05, 10.0, 0.03, (8.5 * sx, 0, 0.01), (0, 0, 0), em))
    for sx in (-1, 1):
        for sy in (-1, 1):
            p.append(box("corner", 0.5, 0.5, 0.12, (8.55 * sx, 5.05 * sy, 0.02), (0, 0, 0), HULL2))
    return join(p, "plate")


def run():
    sc.render.film_transparent = True
    for sec in SECTORS:
        for light in LIGHTS:
            apply_light(sec, light)
            tag = f"{sec}_{light}"
            meta = dict(sector=sec, light=light, level=1, facing=0, part="body")
            for nm, o in build_tiles(sec, light).items():
                show_only([o])
                shoot(f"tile_{nm}_{tag}", TW, TH, 1.0, 0.0, dict(meta, group="tile_" + nm, anim="static", outline=False, kind="tile", notrim=True))
            purge()
            for st in ("empty", "selected", "valid", "invalid"):
                o = build_pad(sec, st)
                show_only([o])
                shoot(f"pad_{st}_{tag}", 96, 96, 1.0, 0.0, dict(meta, group="pad_" + st, anim="static", outline=False, kind="marker"))
                purge()
            for k in (0, 2, 4, 6):
                o = build_gate(sec, k)
                show_only([o])
                shoot(f"gate_f{k}_{tag}", 128, 110, 1.0, 0.3, dict(meta, group="gate", facing=k, anim="static", outline=False, kind="marker"))
                purge()
            for pi in range(12):
                nm, parts = PROPS[sec]()[pi]   # rebuild per prop: purge() below removes every mesh object
                o = join(parts, nm)
                show_only([o])
                shoot(f"prop_{nm}_{tag}", 112, 128, 1.0, 0.5, dict(meta, group="prop_" + nm, anim="static", outline=False, kind="prop"))
                purge()
            o = build_plate(sec)
            show_only([o])
            shoot(f"plate_{tag}", 900, 460, 1.0, -0.2, dict(meta, group="plate", anim="static", outline=False, kind="plate", notrim=True), ppu=50.0)
            purge()
    apply_light("cradle", "dusk")
