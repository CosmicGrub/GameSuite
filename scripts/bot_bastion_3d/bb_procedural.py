"""Procedural (non-Blender) sprites: FX strips, glows, shadow blob, range-ring decals, shield domes,
lane chevrons and sector backdrops. Pure Pillow + numpy; original, generated by project scripts.
Each generator yields (name, PIL.Image RGBA, meta) with meta keys: group, anim, frame, anchor=(ax, ay)|None
(None = image centre), kind, plus optional sector/light."""
import math, random
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

SIN = math.sin(math.radians(50))


def hexc(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def canvas(w, h):
    return np.zeros((h, w, 4), np.float32)


def blend(c, rgb, a):
    """over-composite colour rgb (0..255 tuple) with alpha mask a (h,w) onto c (premult-free float rgba 0..1)."""
    a = np.clip(a, 0, 1)[..., None]
    col = np.array(rgb, np.float32) / 255.0
    oa = c[..., 3:4]
    na = a + oa * (1 - a)
    with np.errstate(invalid="ignore", divide="ignore"):
        rgbn = np.where(na > 1e-6, (col * a + c[..., :3] * oa * (1 - a)) / np.maximum(na, 1e-6), 0)
    c[..., :3] = rgbn
    c[..., 3:4] = na


def to_img(c):
    return Image.fromarray((np.clip(c, 0, 1) * 255 + 0.5).astype(np.uint8), "RGBA")


def grid(w, h):
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    return x - w / 2 + 0.5, y - h / 2 + 0.5


def radial(w, h, r, soft=0.5, cx=0, cy=0, ry=None):
    x, y = grid(w, h)
    d = np.sqrt(((x - cx) / r) ** 2 + ((y - cy) / (ry or r)) ** 2)
    return np.clip((1 - d) / max(soft, 1e-3), 0, 1)


def ring_mask(w, h, r, thick, ry_scale=1.0, cx=0, cy=0):
    x, y = grid(w, h)
    d = np.sqrt((x - cx) ** 2 + ((y - cy) / ry_scale) ** 2)
    return np.clip(1 - np.abs(d - r) / thick, 0, 1)


def fx_all():
    out = []
    rr = random.Random(5)

    def add(name, c, **m):
        out.append((name, to_img(c), m))

    # glows (white, tint at runtime, additive)
    for nm, s in (("s", 64), ("m", 128), ("l", 192)):
        c = canvas(s, s)
        blend(c, (255, 255, 255), radial(s, s, s / 2, 1.0) ** 1.6)
        add(f"glow_{nm}", c, group=f"glow_{nm}", anim="static", frame=0, kind="fx", blend="additive")
    c = canvas(112, 64)
    blend(c, (0, 0, 0), radial(112, 64, 54, 0.9, ry=30) * 0.38)
    add("shadow_blob", c, group="shadow_blob", anim="static", frame=0, kind="fx", blend="alpha")

    # explosion (Lobber shell): ring + flash + dust, 8 frames, 160px
    for f in range(8):
        t = f / 7
        c = canvas(160, 160)
        blend(c, (120, 96, 80), radial(160, 160, 30 + 44 * t, 0.9, ry=(30 + 44 * t) * 0.8) * (0.55 * (1 - t) ** 1.2))
        blend(c, (255, 181, 71), ring_mask(160, 160, 14 + 56 * t, 7 * (1 - t) + 1.5, 0.8) * (1 - t * 0.8))
        blend(c, (255, 240, 200), radial(160, 160, 46 * (1 - t) + 4, 0.7) * (1 - t) ** 0.8)
        add(f"fx_explosion_{f}", c, group="fx_explosion", anim="boom", frame=f, kind="fx", blend="alpha")

    # kill pop: rock chips + dust, 6 frames, 128px
    ang = [rr.uniform(0, 6.28) for _ in range(5)]
    spd = [rr.uniform(0.6, 1.1) for _ in range(5)]
    for f in range(6):
        t = f / 5
        c = canvas(128, 128)
        blend(c, (150, 120, 104), radial(128, 128, 20 + 30 * t, 0.9) * 0.5 * (1 - t))
        im = Image.new("L", (128, 128), 0)
        d = ImageDraw.Draw(im)
        for a, s in zip(ang, spd):
            px, py = 64 + math.cos(a) * 40 * t * s, 64 + math.sin(a) * 30 * t * s - 14 * math.sin(t * 3.1) * s
            r = 6 * (1 - t * 0.5)
            d.polygon([(px - r, py), (px, py - r), (px + r * 0.8, py + r * 0.3), (px - r * 0.2, py + r)], fill=255)
        blend(c, (168, 120, 106), np.asarray(im, np.float32) / 255 * (1 - t * 0.6))
        add(f"fx_pop_{f}", c, group="fx_pop", anim="pop", frame=f, kind="fx", blend="alpha")

    # sparks, 6 frames, 96px
    sa = [rr.uniform(0, 6.28) for _ in range(7)]
    for f in range(6):
        t = f / 5
        c = canvas(96, 96)
        im = Image.new("L", (96, 96), 0)
        d = ImageDraw.Draw(im)
        for a in sa:
            r0, r1 = 8 + 30 * t, 14 + 36 * t
            d.line([(48 + math.cos(a) * r0, 48 + math.sin(a) * r0 * 0.8), (48 + math.cos(a) * r1, 48 + math.sin(a) * r1 * 0.8)], fill=255, width=2)
        blend(c, (255, 232, 160), np.asarray(im.filter(ImageFilter.GaussianBlur(0.6)), np.float32) / 255 * (1 - t * 0.7))
        add(f"fx_spark_{f}", c, group="fx_spark", anim="spark", frame=f, kind="fx", blend="additive")

    # dust puff, 6 frames, 112px
    for f in range(6):
        t = f / 5
        c = canvas(112, 112)
        for k, (ox, oy) in enumerate(((-14, 4), (10, 8), (0, -8), (18, -2))):
            blend(c, (160, 148, 140), radial(112, 112, 12 + 22 * t, 0.9, cx=ox * (0.6 + t), cy=oy * (0.6 + t), ry=(12 + 22 * t) * 0.8) * 0.45 * (1 - t))
        add(f"fx_dust_{f}", c, group="fx_dust", anim="puff", frame=f, kind="fx", blend="alpha")

    # freeze pulse (Tender): mint ring on the ground + ice facets, 6 frames, 192x128
    for f in range(6):
        t = f / 5
        c = canvas(192, 128)
        blend(c, (107, 255, 158), ring_mask(192, 128, 20 + 66 * t, 5 * (1 - t) + 1.5, SIN) * (1 - t * 0.75))
        blend(c, (160, 255, 210), radial(192, 128, 20 + 60 * t, 0.9, ry=(20 + 60 * t) * SIN) * 0.22 * (1 - t))
        im = Image.new("L", (192, 128), 0)
        d = ImageDraw.Draw(im)
        for k in range(8):
            a = k * 0.785 + 0.3
            r = (20 + 66 * t)
            x, y = 96 + math.cos(a) * r, 64 + math.sin(a) * r * SIN
            d.polygon([(x, y - 6), (x + 3, y), (x, y + 3), (x - 3, y)], fill=255)
        blend(c, (230, 255, 255), np.asarray(im, np.float32) / 255 * (1 - t))
        add(f"fx_freeze_{f}", c, group="fx_freeze", anim="pulse", frame=f, kind="fx", blend="additive")

    # nova ring, 6 frames, 400x260 (radius up to ~1.9 u at baked ppu)
    for f in range(6):
        t = f / 5
        c = canvas(400, 260)
        blend(c, (255, 255, 255), ring_mask(400, 260, 20 + 170 * t, 9 * (1 - t) + 2, SIN) * (1 - t * 0.7))
        blend(c, (200, 230, 255), ring_mask(400, 260, 14 + 160 * t, 22 * (1 - t) + 4, SIN) * 0.25 * (1 - t))
        add(f"fx_nova_{f}", c, group="fx_nova_ring", anim="pulse", frame=f, kind="fx", blend="additive")

    # repair: mint plus signs rising, 6 frames, 128px
    for f in range(6):
        t = f / 5
        c = canvas(128, 128)
        im = Image.new("L", (128, 128), 0)
        d = ImageDraw.Draw(im)
        for k, ox in enumerate((-26, 0, 26)):
            y = 100 - t * 70 - k * 8
            d.rectangle([64 + ox - 2, y - 8, 64 + ox + 2, y + 8], fill=255)
            d.rectangle([64 + ox - 8, y - 2, 64 + ox + 8, y + 2], fill=255)
        blend(c, (107, 255, 158), np.asarray(im.filter(ImageFilter.GaussianBlur(0.5)), np.float32) / 255 * (1 - t * 0.6))
        blend(c, (107, 255, 158), ring_mask(128, 128, 30 + 20 * t, 3, SIN, cy=22) * (1 - t) * 0.6)
        add(f"fx_repair_{f}", c, group="fx_repair", anim="rise", frame=f, kind="fx", blend="additive")

    # hit flash, 2 frames, 64px
    for f in range(2):
        c = canvas(64, 64)
        blend(c, (255, 255, 255), radial(64, 64, 26 - 10 * f, 0.6))
        add(f"fx_hit_{f}", c, group="fx_hit_flash", anim="flash", frame=f, kind="fx", blend="additive")

    # muzzle flashes (tintable colours baked), 64px
    for nm, col in (("cyan", "#4FE3FF"), ("amber", "#FFB547"), ("violet", "#B58CFF"), ("magenta", "#FF4FD8")):
        c = canvas(64, 64)
        blend(c, hexc(col), radial(64, 64, 28, 1.0) ** 1.4)
        blend(c, (255, 255, 255), radial(64, 64, 12, 0.8))
        add(f"fx_muzzle_{nm}", c, group=f"fx_muzzle_{nm}", anim="flash", frame=0, kind="fx", blend="additive")

    # build / upgrade rings (cyan-white), 6 frames, 160x120
    for f in range(6):
        t = f / 5
        c = canvas(160, 120)
        blend(c, (180, 240, 255), ring_mask(160, 120, 24 + 40 * t, 4 * (1 - t) + 1.5, SIN, cy=-30 * t + 10) * (1 - t * 0.6))
        im = Image.new("L", (160, 120), 0)
        d = ImageDraw.Draw(im)
        for k in range(5):
            a = k * 1.2566
            x, y = 80 + math.cos(a) * 30, 70 + math.sin(a) * 30 * SIN - t * 50
            d.rectangle([x - 2, y - 2, x + 2, y + 2], fill=255)
        blend(c, (255, 255, 255), np.asarray(im, np.float32) / 255 * (1 - t * 0.5))
        add(f"fx_build_{f}", c, group="fx_build_ring", anim="rise", frame=f, kind="fx", blend="additive", anchor=(80, 84))

    # shield dome (Core), 3 intensity states, 440x300; anchor = ground centre
    W, H = 440, 368
    R = 200.0
    x, y = grid(W, H)
    cy0 = 20  # ground centre y offset (px below image centre)
    yy = y - cy0
    up = -yy
    inside = ((x ** 2 + up ** 2 <= R * R) & (up >= 0)) | ((x ** 2 / R ** 2 + (yy / (R * SIN)) ** 2 <= 1) & (up < 0))
    edge = np.where(up >= 0, np.abs(np.sqrt(x ** 2 + up ** 2) - R), np.abs(np.sqrt(x ** 2 + (yy / SIN) ** 2) - R) * SIN)
    hexm = np.zeros((H, W), np.float32)
    s = 34.0
    # hex grid lines in screen space
    for k in range(3):
        ang = k * math.pi / 3
        u = x * math.cos(ang) + y * math.sin(ang)
        hexm = np.maximum(hexm, np.clip(1 - np.abs((u % s) - s / 2) / 1.0, 0, 1) * 0.0)
    hx = np.abs((x % s) - s / 2)
    hy = np.abs((y % (s * 0.86)) - s * 0.43)
    lines = np.clip(1 - np.minimum(np.abs(hx - s / 4), np.abs(hy - s * 0.215)) / 1.2, 0, 1)
    for st, (fa, la, ea) in enumerate(((0.05, 0.10, 0.35), (0.12, 0.22, 0.65), (0.20, 0.35, 0.95))):
        c = canvas(W, H)
        m = inside.astype(np.float32)
        blend(c, (95, 168, 255), m * fa)
        blend(c, (150, 210, 255), m * lines * la)
        blend(c, (190, 235, 255), np.clip(1 - edge / 3.0, 0, 1) * m * ea)
        add(f"shield_dome_{st}", c, group="shield_dome", anim="state", frame=st, kind="fx", blend="alpha", anchor=(W / 2, H / 2 + cy0))
    for f in range(4):  # hit ripple on the dome
        t = f / 3
        c = canvas(W, H)
        rm = ring_mask(W, H, 40 + 150 * t, 6, 1.0, cy=-30)
        blend(c, (190, 235, 255), rm * inside * (1 - t) * 0.9)
        add(f"shield_ripple_{f}", c, group="shield_ripple", anim="ripple", frame=f, kind="fx", blend="additive", anchor=(W / 2, H / 2 + cy0))

    # lane chevrons (white, tintable): east-flowing "h" and north-flowing "v", 4 phase frames, 100x77
    for orient in ("h", "v"):
        for f in range(4):
            c = canvas(100, 77)
            im = Image.new("L", (400, 308), 0)
            d = ImageDraw.Draw(im)
            ph = (f / 4.0)
            for k in range(2):
                p = ((ph + k * 0.5) % 1.0)
                if orient == "h":
                    cx = 400 * p
                    d.line([(cx - 28, 154 - 62), (cx, 154), (cx - 28, 154 + 62)], fill=255, width=14)
                else:
                    cy = 308 * (1 - p)
                    d.line([(200 - 62, cy + 28 * SIN * 2), (200, cy), (200 + 62, cy + 28 * SIN * 2)], fill=255, width=14)
            a = np.asarray(im.resize((100, 77), Image.LANCZOS), np.float32) / 255 * 0.55
            blend(c, (255, 255, 255), a)
            add(f"fx_chevron_{orient}_{f}", c, group=f"fx_chevron_{orient}", anim="flow", frame=f, kind="tile", blend="alpha", notrim=True, anchor=(50, 38.5))

    # range-ring decals (white, tinted at runtime). Unit radius 3.0 u at ppu 100 -> 600 x 460; stroke ~3 px.
    RW, RH, RAD = 612, 472, 300.0
    def ring_img(style):
        ss = 2
        im = Image.new("L", (RW * ss, RH * ss), 0)
        d = ImageDraw.Draw(im)
        cx, cy = RW * ss / 2, RH * ss / 2
        def ell(r, width, dashes=None, step=None):
            n = 720
            pts = [(cx + r * ss * math.cos(2 * math.pi * i / n), cy + r * ss * SIN * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]
            if dashes is None:
                d.line(pts, fill=255, width=int(width * ss), joint="curve")
            else:
                on, off = dashes
                i = 0
                while i < n:
                    seg = pts[i:i + on + 1]
                    if len(seg) > 1:
                        d.line(seg, fill=255, width=int(width * ss))
                    i += on + off
        def dots(r, k, rad):
            for i in range(k):
                a = 2 * math.pi * i / k
                x, y = cx + r * ss * math.cos(a), cy + r * ss * SIN * math.sin(a)
                d.ellipse([x - rad * ss, y - rad * ss, x + rad * ss, y + rad * ss], fill=255)
        if style == "solid":
            ell(RAD, 3)
        elif style == "dashed":
            ell(RAD, 3, (14, 8))
        elif style == "dotted":
            dots(RAD, 90, 2.4)
        elif style == "double":
            ell(RAD, 3)
            ell(RAD - 9, 2)
        elif style == "blindspot":
            ell(RAD, 3, (14, 8))
            ell(RAD * 0.34, 3)
        a = np.asarray(im.resize((RW, RH), Image.LANCZOS), np.float32) / 255
        x, y = grid(RW, RH)
        fill = (np.sqrt(x ** 2 + (y / SIN) ** 2) <= RAD).astype(np.float32) * 0.14
        if style == "blindspot":
            fill *= (np.sqrt(x ** 2 + (y / SIN) ** 2) >= RAD * 0.34)
        c = canvas(RW, RH)
        blend(c, (255, 255, 255), np.maximum(a, fill))
        return c
    for st in ("solid", "dashed", "dotted", "double", "blindspot"):
        add(f"range_{st}", ring_img(st), group=f"range_{st}", anim="static", frame=0, kind="decal", blend="alpha", baked_radius_u=3.0)
    return out


# ------------------------------------------------------------------------------------------------ backdrops
SECT = {
    "cradle": dict(top="#070A1C", bot="#17224E", acc="#4FE3FF"),
    "glass": dict(top="#04101A", bot="#12384A", acc="#9DEBFF"),
    "ember": dict(top="#120606", bot="#4A1E16", acc="#FF8A3D"),
    "hush": dict(top="#0A0618", bot="#2E2058", acc="#B58CFF"),
}


def backdrops():
    out = []
    W, H = 512, 288
    for sec, s in SECT.items():
        for light in ("dusk", "night", "alarm"):
            rnd = random.Random(hash((sec, 1)) & 0xffff if False else (len(sec) * 97 + ord(sec[0])))
            gain = {"dusk": 1.0, "night": 0.55, "alarm": 0.9}[light]
            top, bot = np.array(hexc(s["top"]), np.float32), np.array(hexc(s["bot"]), np.float32)
            t = np.linspace(0, 1, H, dtype=np.float32)[:, None, None]
            far = (top * (1 - t) + bot * t) * gain
            far = np.repeat(far, W, axis=1)
            if light == "alarm":
                far = far + np.array([60, 6, 4], np.float32) * (t ** 2)
            c = canvas(W, H)
            c[..., :3] = np.clip(far, 0, 255) / 255
            c[..., 3] = 1
            n = 140 if light == "night" else 90
            for _ in range(n):
                x, y = rnd.randrange(W), rnd.randrange(int(H * 0.8))
                b = rnd.uniform(0.3, 1.0) * (1.2 if light == "night" else 0.8)
                c[y, x, :3] = np.clip(c[y, x, :3] + b * 0.9, 0, 1)
            out.append((f"backdrop_far_{sec}_{light}", to_img(c), dict(group="backdrop_far", sector=sec, light=light, anim="static", frame=0, kind="backdrop", parallax=0.1)))
            # mid layer: sector silhouettes, transparent
            m = canvas(W, H)
            acc = hexc(s["acc"])
            if sec == "cradle":
                for k in range(7):
                    cx, cy, r = rnd.randrange(W), rnd.randrange(120, 260), rnd.randrange(12, 36)
                    blend(m, (30, 38, 80), radial(W, H, r, 0.15, cx - W / 2, cy - H / 2, ry=r * 0.7))
                blend(m, acc, ring_mask(W, H, 210, 1.5, 0.35, cy=60) * 0.35)
            elif sec == "glass":
                for k in range(26):
                    x0 = rnd.randrange(W); hh = rnd.randrange(30, 110)
                    im = Image.new("L", (W, H), 0)
                    ImageDraw.Draw(im).polygon([(x0 - 7, H), (x0, H - hh), (x0 + 7, H)], fill=255)
                    blend(m, (40, 120, 150), np.asarray(im, np.float32) / 255 * 0.85)
                xs = np.arange(W)[None, :]
                band = np.exp(-(((np.arange(H)[:, None] - (70 + 20 * np.sin(xs / 60.0))) / 14.0) ** 2))
                blend(m, (120, 255, 230), band * 0.25)
            elif sec == "ember":
                xs = np.arange(W)
                ridge = H - 60 - 34 * np.abs(np.sin(xs / 37.0)) - 20 * np.abs(np.sin(xs / 11.0 + 2))
                mask = (np.arange(H)[:, None] >= ridge[None, :]).astype(np.float32)
                blend(m, (24, 10, 10), mask)
                blend(m, acc, np.clip(1 - np.abs(np.arange(H)[:, None] - ridge[None, :]) / 4.0, 0, 1) * 0.8)
                blend(m, acc, radial(W, H, 240, 1.0, 0, H / 2, ry=70) * 0.25)
            else:
                for k in range(4):
                    cy = rnd.randrange(150, 270)
                    blend(m, (150, 120, 230), np.exp(-(((np.arange(H)[:, None] - cy) / 14.0) ** 2)) * np.ones((1, W), np.float32) * 0.16)
                for k in range(9):
                    x0, h0 = rnd.randrange(W), rnd.randrange(60, 120)
                    blend(m, (40, 32, 80), np.clip(1 - np.abs(np.arange(W)[None, :] - x0) / 1.5, 0, 1) * (np.arange(H)[:, None] > H - h0))
                    blend(m, (232, 220, 255), radial(W, H, 5, 0.9, x0 - W / 2, H - h0 - H / 2) * 0.9)
            ma = m.copy()
            ma[..., 3] *= {"dusk": 1.0, "night": 0.8, "alarm": 1.0}[light]
            ma[..., :3] *= gain ** 0.5
            out.append((f"backdrop_mid_{sec}_{light}", to_img(ma), dict(group="backdrop_mid", sector=sec, light=light, anim="static", frame=0, kind="backdrop", parallax=0.3)))
            # near layer: soft bokeh specks
            nr = canvas(W, H)
            for k in range(14):
                cx, cy, r = rnd.randrange(W), rnd.randrange(H), rnd.randrange(8, 26)
                blend(nr, acc, radial(W, H, r, 0.8, cx - W / 2, cy - H / 2) * rnd.uniform(0.04, 0.1))
            out.append((f"backdrop_near_{sec}_{light}", to_img(nr), dict(group="backdrop_near", sector=sec, light=light, anim="static", frame=0, kind="backdrop", parallax=0.6)))
    return out
